from django.core.management.base import BaseCommand

from catalog.models import Category, Part


class Command(BaseCommand):
    help = 'Seed the catalog with demo heavy equipment parts.'

    def handle(self, *args, **options):
        catalog = {
            'Двигатели и комплектующие': [
                ('Двигатели и комплектующие', 'Запасные части и комплектующие для двигателей экскаваторов, бульдозеров, погрузчиков и другой спецтехники.'),
                ('Детали двигателя', 'Комплектующие двигателя для строительной и дорожно-строительной техники.'),
            ],
            'Гидравлика': [
                ('Гидронасосы', 'Гидронасосы и компоненты гидравлических систем спецтехники.'),
                ('Компоненты гидравлики', 'Запасные части для гидравлических систем строительных машин.'),
            ],
            'Фильтры и ремни': [
                ('Фильтры для спецтехники', 'Фильтрующие элементы для двигателей и систем спецтехники.'),
                ('Приводные ремни', 'Ремни для приводных систем строительной и дорожной техники.'),
            ],
            'Турбины и топливные системы': [
                ('Турбины', 'Турбокомпрессоры для двигателей спецтехники.'),
                ('Топливные системы', 'Компоненты топливных систем строительных и дорожных машин.'),
            ],
            'Ходовая часть и редукторы': [
                ('Ходовая часть', 'Комплектующие ходовой части экскаваторов и другой гусеничной техники.'),
                ('Редукторы', 'Редукторы и компоненты трансмиссии строительной техники.'),
            ],
            'Тормозные системы': [
                ('Тормозные системы спецтехники', 'Компоненты тормозных систем строительной и дорожно-строительной техники.'),
            ],
        }

        legacy_demo_parts = [
            'Свечи зажигания',
            'Ремень ГРМ',
            'Топливный фильтр',
            'Тормозные колодки',
            'Тормозной диск',
            'Масляный фильтр',
            'Воздушный фильтр',
            'Амортизатор',
            'Рычаг подвески',
            'Аккумулятор',
            'Стартер',
            'Диагностика',
            'Ремонт подвески',
        ]
        Part.objects.filter(
            name__in=legacy_demo_parts,
            category__name__in=['Двигатель', 'Тормоза', 'Фильтры', 'Подвеска', 'Электрика', 'Сервис'],
        ).update(is_active=False)

        created = 0
        for category_name, parts in catalog.items():
            category, _ = Category.objects.get_or_create(name=category_name)
            for part_name, description in parts:
                _, part_created = Part.objects.get_or_create(
                    category=category,
                    name=part_name,
                    defaults={'description': description, 'is_active': True},
                )
                if part_created:
                    created += 1

        self.stdout.write(self.style.SUCCESS(f'Seeded catalog entries: {created} new parts.'))
